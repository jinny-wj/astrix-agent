import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { generateKrn, generateTheme } from './local-generators.mjs';

const fixture = JSON.parse(await readFile(new URL('./fixtures/basic-schema.json', import.meta.url), 'utf8'));
const result = await generateKrn(fixture);
assert.equal(result.engine, 'recovered-original-krn');
assert.equal(result.offline, true);
assert.deepEqual(result.files.map(file => file.path), ['App.tsx', 'styles.ts']);
assert.match(result.files[0].content, /本地恢复的原 KRN 引擎/);
assert.match(result.files[0].content, /react-native/);
assert.match(result.files[1].content, /StyleSheet\.create/);
assert.match(result.files[1].content, /320/);
const gradient = structuredClone(fixture);
gradient.nodeTree.styles.gradient = [{ type:'GRADIENT_LINEAR', gradientTransform:[[1,0,0],[0,1,0]], gradientStops:[{position:0,color:{r:1,g:0,b:0,a:1}},{position:1,color:{r:0,g:0,b:1,a:1}}] }];
const gradientResult = await generateKrn(gradient);
assert.match(gradientResult.files[0].content, /LinearGradient/);
assert.match(gradientResult.files[0].content, /#f00/);
const theme = { styles:{primary:'#165dff'},variables:{spacing:8},variableCollection:[{name:'Local'}] };
const themeResult = await generateTheme(theme);
assert.deepEqual(themeResult.files.map(file => file.path), ['styles.json','variables.json','variable-collection.json']);
assert.deepEqual(JSON.parse(themeResult.files[0].content), theme.styles);
await assert.rejects(generateTheme({...theme,imageNodes:[{id:'not-connected'}]}), /真实 Figma/);
await assert.rejects(generateKrn({nodeTree:{id:'x',nodeType:'unknown',styles:{}}}), /nodeType/);
const output = new URL('./verification-output/', import.meta.url);
await mkdir(output,{recursive:true});
for (const file of result.files) await writeFile(new URL(file.path,output),file.content);
await writeFile(new URL('verification.json',output),JSON.stringify({success:true,checks:['original KRN view/text compilation','original gradient helper and LinearGradient output','original theme three JSON outputs','unsupported Figma image export rejected','invalid schema rejected'],sourceSha256:result.sourceSha256},null,2)+'\n');
console.log('PASS: original KRN view/text, gradients, theme export, and invalid-input boundaries.');
